#!/usr/bin/env python3
"""Generate the profile's context, its vocabulary, the refusal list and the controls list from their one
definitions, and refuse drift (HonestFramework's templates/check_generated.py pattern; study QRO-0, section 13).

    python tools/gen_vocabulary.py --write    # regenerate, after changing qro/vocabulary.py or controls/registry.py
    python tools/gen_vocabulary.py --check    # fail if a committed file is not what its definition renders

The definitions are qro/vocabulary.py and controls/registry.py; the files are:
  - profile/context.jsonld, the context a crate's @context carries after RO-Crate 1.3's;
  - docs/VOCABULARY.md, the profile's vocabulary: kinds, absence words, spellings, words, terms, types, and the
    custody log's and audit record's fields. Each term has an anchor, which its IRI names;
  - docs/REFUSALS.md, every refusal and where it is raised;
  - docs/CONTROLS.md, every control of section 11 and its owner.
Exit 0: every file is exactly what its definition renders. 1: drift, with a diff, or a file missing. 2: the
definition contradicts itself. Stdlib only.
"""
import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from controls import registry as C  # noqa: E402
from qro import vocabulary as V  # noqa: E402

BANNER = "<!-- GENERATED by tools/gen_vocabulary.py from {src}. Edit the definition and run --write. -->\n\n"


def cell(s):
    return str(s).replace("|", "\\|")


def context_jsonld():
    return json.dumps({"@context": V.context()[1]}, ensure_ascii=True, sort_keys=True, indent=2) + "\n"


def vocabulary_md():
    out = [BANNER.format(src="qro/vocabulary.py"), f"# The QRO-Crate vocabulary, profile version {V.PROFILE_VERSION}\n\n",
           "Every term a crate may use, with its kind, its one spelling, and the checker step that re-derives it "
           "if it is CHECKED. A key RO-Crate 1.3's context defines but this list does not is refused as "
           "`field-kind`; a key neither names is `term-unknown` (study QRO-0, rule 9).\n\n",
           f"The prefix `{V.PREFIX}` is `{V.NAMESPACE}`, provisional (question 6): each `{V.PREFIX}` term's IRI "
           "is this page with the term's anchor.\n\n",
           "## Kinds (rule 1)\n\n| kind | meaning |\n|---|---|\n"]
    out += [f"| {k} | {cell(m)} |\n" for k, m in V.KINDS.items()]
    out += ["\n## Absence words (rule 2)\n\n| word | meaning |\n|---|---|\n"]
    out += [f"| `{k}` | {cell(m)} |\n" for k, m in V.ABSENCE.items()]
    out += ["\n## Spellings (section 9)\n\n| spelling | its one form |\n|---|---|\n"]
    out += [f"| {k} | {cell(m)} |\n" for k, m in V.SPELLINGS.items()]
    out += ["\n## Word sets\n\n| set | word | meaning |\n|---|---|---|\n"]
    out += [f"| {s} | `{w}` | {cell(m)} |\n" for s, ws in V.WORDS.items() for w, m in ws.items()]
    out += ["\n## Terms\n\n", "A list-valued term is always a sorted list of distinct values; any other never a list. "
            "A header term is one two writers of one crate make differently, normalised away before the crate's "
            "body is compared or digested (rule 4).\n\n",
            "A term stands only on the entities its domain admits: `*` any, `./` the root, the descriptor, "
            "`local-file` a File the crate holds, or a type. The root carries every one of: "
            + ", ".join(f"`{k}`" for k in V.ROOT_REQUIRED) + ".\n\n",
            "| term | kind | spelling | list | absent as | part | step | domain | owner | meaning |\n",
            "|---|---|---|---|---|---|---|---|---|---|\n"]
    for t in V.TERMS:
        anchor = f'<a id="{t.key[len(V.PREFIX) + 1:]}"></a>' if t.key.startswith(V.PREFIX + ":") else ""
        out.append(f"| {anchor}`{t.key}` | {t.kind} | {t.spelling} | {'yes' if t.many else 'no'} | "
                   f"{', '.join(f'`{a}`' for a in t.absent) or '-'} | {t.part} | {t.step or '-'} | "
                   f"{', '.join(f'`{d}`' for d in t.domain)} | {t.owner} | {cell(t.meaning)} |\n")
    out += ["\n## Types\n\n| type | action | owner | meaning |\n|---|---|---|---|\n"]
    for t in V.TYPES:
        anchor = f'<a id="{t.key[len(V.PREFIX) + 1:]}"></a>' if t.key.startswith(V.PREFIX + ":") else ""
        out.append(f"| {anchor}`{t.key}` | {'yes' if t.action else 'no'} | {t.owner} | {cell(t.meaning)} |\n")
    out += ["\n## The custody log's lines and the audit record (section 9.2)\n\n",
            "| record | field | kind | spelling | list | absent as | meaning |\n|---|---|---|---|---|---|---|\n"]
    rows = [(f"custody line, {e}", f) for e, fs in V.CUSTODY_LINE.items() for f in fs]
    rows += [("audit record", f) for f in V.AUDIT_RECORD]
    for name, f in rows:
        out.append(f"| {name} | `{f.key}` | {f.kind} | {f.spelling} | {'yes' if f.many else 'no'} | "
                   f"{', '.join(f'`{a}`' for a in f.absent) or '-'} | {cell(f.meaning)} |\n")
    return "".join(out)


def refusals_md():
    out = [BANNER.format(src="qro/vocabulary.py"), "# Refusals\n\n",
           "Every name the checker, the comparison, the kit or the custody check refuses by, and the labels a kept "
           "record carries. A crate is accepted or refused by one of these names, at a location (study QRO-0, "
           "section 10).\n\n| name | where | effect | owner | meaning |\n|---|---|---|---|---|\n"]
    out += [f"| `{r.name}` | {r.where} | {r.effect} | {r.owner} | {cell(r.meaning)} |\n" for r in V.REFUSALS]
    return "".join(out)


def controls_md():
    built = set(C.PLANTS)
    out = [BANNER.format(src="controls/registry.py"), "# Controls\n\n",
           "Study QRO-0's section 11: each control one planted fault, refused by the name given or stated as the "
           "study says. `python -m controls.run` runs every built one; the rest are pending their parcel.\n\n",
           "| control | planted fault | expected | owner | built |\n|---|---|---|---|---|\n"]
    out += [f"| `{c.name}` | {cell(c.fault)} | {cell(c.text)} | {c.owner} | {'yes' if c.name in built else 'pending'} |\n"
            for c in C.CONTROLS]
    return "".join(out)


OUTPUTS = {"profile/context.jsonld": context_jsonld, "docs/VOCABULARY.md": vocabulary_md,
           "docs/REFUSALS.md": refusals_md, "docs/CONTROLS.md": controls_md}


def problems():
    out = V.sanity()
    for c in C.CONTROLS:
        if c.refusal is not None and c.refusal not in V.REFUSAL:
            out.append(f"control {c.name}: {c.refusal} is not a refusal")
        if c.expected not in ("refused", "accepted", "states"):
            out.append(f"control {c.name}: expected {c.expected}")
    for name in C.PLANTS:
        if name not in C.CONTROL:
            out.append(f"plant {name} names no control")
    return out


def drift(root):
    """[(file, what is wrong)] for each output under `root` that is not exactly what its definition renders."""
    out = []
    for rel, render in OUTPUTS.items():
        path = root / rel
        if not path.is_file():
            out.append((rel, "missing; run --write"))
            continue
        have, want = path.read_bytes().decode("utf-8", errors="replace"), render()
        if have != want:
            diff = "".join("  " + line if line.endswith("\n") else "  " + line + "\n" for line in
                           difflib.unified_diff(have.splitlines(True), want.splitlines(True), "committed",
                                                "definition", n=2))
            out.append((rel, "DRIFTED from its definition:\n" + diff))
    return out


def main(argv=None, root=ROOT):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    found = problems()
    if found:
        sys.stderr.write("the definitions contradict themselves:\n" + "".join(f"  {p}\n" for p in found))
        return 2
    if args.write:
        for rel, render in OUTPUTS.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_bytes(render().encode("utf-8"))
            print(f"wrote {rel}")
        return 0
    bad = drift(root)
    for rel, what in bad:
        sys.stderr.write(f"{rel} {what}")
        sys.stderr.write("  Fix by changing the definition and running --write; editing the file is never the fix.\n")
    for rel in OUTPUTS:
        if rel not in {b for b, _ in bad}:
            print(f"{rel} is exactly what its definition renders")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
