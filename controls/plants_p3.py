"""P3's controls (study QRO-0, section 11; P3's design, item 9, with its correction 1 of 2026-11-08T10:50:42Z; P3.1),
each planted in P1's twin with P1's toolkit (controls/plants_p1.py), as comparisons: a plant returns a `Compared`, whose
outcome is the comparison check's (controls/registry.py's docstring; FORMAT.md item 24).

T is P1's twin. T2 is a second copy of it in which the morning coherence job is re-identified (`forge_t2`): a new job
id; new salts for its two circuits, so new commitments in the manifest, the line, the records and IBM's echo inside the
raw result; one shot of its first PUB moved; the read's two records of it re-identified and renamed, with their
MANIFEST entries; every digest the records hold over what changed resealed; and the metadata regenerated by P1's
generator. In T2 it follows the same morning known answer as in T, so the two crates share exactly that job (its job
id, its commitment and its raw result), which holds no Pub a measure reads.

| control | the plant | comes out |
|---|---|---|
| self-compare | T against T, one selector in both runs, the comparison crate written by hand (`make` refuses it) | `comparison-trivial`: the same job id |
| resealed-compare | T against P1's `shot_moved_resealed` copy of it, coherence job against coherence job, written by hand | `comparison-trivial`: the two share job ids and commitments |
| shared-control | T's {morning known answer, coherence} against T2's, made by `make` | accepted |
| joint-omission | that comparison, its record rewritten to offer per-cause tolerance checks that each pass, and `agree` where the data give `unresolved`; the metadata regenerated | `comparison-generated` |
| readout-unbounded | T's coherence against T2's: the one known-answer pattern {0, 1, 3, 7, 12} serves both | states "isolated as quantum: no, readout's effect unbounded" |

`readout-unbounded`'s twin, two of P5's unit twins whose controls hold a known answer and its complement, is P3.2's:
until then it has a STATEMENTS entry and no TWINS entry, and the runner prints it pending. This module builds nothing
when it is imported: T2 is forged once in a process, when a plant first asks for it.
"""
import atexit
import hashlib
import json
import shutil
import tempfile
from pathlib import Path

from controls import plants_p1
from controls.registry import Compared
from qro import canonical, p1_commit, p1_records, p3_compare, p3_declaration, p3_record
from qro import vocabulary as V

DEVICE = "ibm_kingston"
MORNING_MANIFEST = f"{plants_p1.MORNING_BUNDLE}/manifest.json"
COHERENCE_LINE = f"{plants_p1.MORNING_RUN}/coherence-line.json"
COHERENCE_METRICS = f"{plants_p1.MORNING_RUN}/coherence-metrics.json"
COHERENCE_RECORDS = (f"{plants_p1.MORNING_RUN}/coherence-pub0-coherence-xx.json",
                     f"{plants_p1.MORNING_RUN}/coherence-pub1-coherence-yy.json")
NEW_JOB = "d" + "p3" + "t" * 17               # the shape of an IBM job id that is nobody's: 20 letters and digits
COHERENCES = ("x0x1", "y0y1")
CAUSE_CHECKS = [{"cause": "routing alone", "effect": "417/10000", "epsilon": "1/20", "within": "yes"},
                {"cause": "angle bias alone", "effect": "497/10000", "epsilon": "1/20", "within": "yes"}]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def _renamed(x, old, new):
    """A JSON value with `old` replaced by `new` in every string it holds, a key's among them."""
    if isinstance(x, dict):
        return {_renamed(k, old, new): _renamed(v, old, new) for k, v in x.items()}
    if isinstance(x, list):
        return [_renamed(v, old, new) for v in x]
    return x.replace(old, new) if isinstance(x, str) else x


def forge_t2(crate):
    """The twin's morning coherence job re-identified in `crate`, a copy of the twin, as the module's docstring says;
    the metadata regenerated. Returns the crate."""
    f = plants_p1.Forge(crate)
    old = f.job_id(COHERENCE_LINE)
    manifest = f.json(MORNING_MANIFEST)
    circuits = next(j for j in manifest["jobs"] if j["job"] == "coherence")["circuits"]
    commitments = []
    for k, c in enumerate(circuits):
        c["salt"] = sha(b"P3.1's T2: " + c["salt"].encode("ascii"))[:len(c["salt"])]
        record = f.json(COHERENCE_RECORDS[k])
        fields = p1_records.device_run(f.read(COHERENCE_RECORDS[k]), COHERENCE_RECORDS[k]).fields(COHERENCE_RECORDS[k])
        fields["salt"] = c["salt"]
        c["commitment"] = p1_commit.commitment_of(fields)
        commitments.append(c["commitment"])
        record["source"].update(salt=c["salt"], commitment=c["commitment"], job_id=NEW_JOB)
        if k == 0:                                # one shot of the first PUB moved, qubit 0 flipped, so x0x1 moves
            raw = f.read(plants_p1.COHERENCE_RAW)
            first = plants_p1.rows_of(plants_p1.array_of(json.loads(raw), 0)["__value__"])[0][0]
            data, was, now = plants_p1.moved_shot(raw, to=first ^ 1)
            counts = {tuple(q): n for q, n in record["counts"]}
            counts[plants_p1.outcome_of(was)] -= 1
            counts[plants_p1.outcome_of(now)] = counts.get(plants_p1.outcome_of(now), 0) + 1
            record["counts"] = [[list(q), n] for q, n in sorted(counts.items()) if n]
            f.write(plants_p1.COHERENCE_RAW, data)
        f.put_record(COHERENCE_RECORDS[k], record)
    f.put_json(MORNING_MANIFEST, manifest)
    f.reseal_bundle(plants_p1.MORNING_BUNDLE)

    def echoes(doc):
        for k, commitment in enumerate(commitments):
            doc["__value__"]["pub_results"][k]["__value__"]["metadata"]["circuit_metadata"]["qf_commitment"] = commitment
    f.edit_json(plants_p1.COHERENCE_RAW, echoes)
    f.edit_json(COHERENCE_LINE, lambda o: o.update(job_id=NEW_JOB, commitments=commitments))
    f.put_json(COHERENCE_METRICS, _renamed(f.json(COHERENCE_METRICS), old, NEW_JOB))
    raw = f.read(plants_p1.COHERENCE_RAW)
    for top in (plants_p1.REFETCH, plants_p1.RESULTS):
        was, now = f"{top}/{DEVICE}/{old}.json", f"{top}/{DEVICE}/{NEW_JOB}.json"
        doc = _renamed(f.json(was), old, NEW_JOB)
        if top == plants_p1.REFETCH:
            for k, p in enumerate(doc["holds"]["pubs"]):
                p["commitment_in_ibm_copy"] = p["commitment_in_line"] = commitments[k]
        else:
            for key in ("committed", "ibm_copy"):
                doc[key]["bytes"], doc[key]["sha256"] = len(raw), sha(raw)
        Path(crate).joinpath(*was.split("/")).unlink()
        f.put_json(now, doc)
        data = f.read(now)

        def entry(m, was=was, now=now, data=data, top=top):
            for e in m["files"]:
                if e["path"] == was[len(top) + 1:]:
                    e.update(path=now[len(top) + 1:], bytes=len(data), sha256=sha(data))
        f.edit_json(f"{top}/MANIFEST.json", entry)
    return plants_p1.rebuild(crate)


_T2 = []


def pristine_t2():
    """T2, forged once in this process in a directory of the system's temporary files that nothing writes to again;
    removed when the process ends."""
    if not _T2:
        d = Path(tempfile.mkdtemp(prefix="p3-t2-"))
        atexit.register(shutil.rmtree, str(d), True)
        _T2.append(forge_t2(plants_p1.twin_crate(d)))
    return _T2[0]


def t2_crate(dest):
    """A fresh copy of T2, in dest/crate."""
    out = Path(dest) / "crate"
    shutil.copytree(pristine_t2(), out)
    return out


def identity(crate):
    return canonical.body_digest(plants_p1.graph_of(crate))


def morning(crate):
    """The digest of a twin's morning bundle: its manifest's SHA-256, which its lines hold."""
    return sha(plants_p1.read_file(crate, MORNING_MANIFEST))


def selector(crate):
    """The morning bundle of a twin, on kingston: its known answer and its coherence job."""
    return {"bundles": [morning(crate)], "device": DEVICE}


def declaration(a, b, epsilon="0/1", kind="real", measures=COHERENCES):
    """The declaration of the coherences of crate `a`'s morning bundle against crate `b`'s."""
    plan = p3_declaration.plan({m: epsilon for m in measures}, {"a": selector(a), "b": selector(b)}, kind=kind)
    return p3_declaration.write({"a": [identity(a)], "b": [identity(b)]}, plan)


def hand_written(out, declaration_bytes, record_bytes):
    """A comparison crate written with no check, which `make` would refuse to write: its declaration, a record, and
    the metadata its generator makes, written by qro.canonical.write. Returns its directory."""
    out = Path(out)
    for rel, data in ((p3_record.DECLARATION, declaration_bytes), (p3_record.RECORD, record_bytes)):
        plants_p1.write_file(out, rel, data)
    plants_p1.write_file(out, canonical.DESCRIPTOR, canonical.write(p3_record.generate(out)))
    return out


PLACEHOLDER = canonical.dumps({"format": p3_record.RECORD_FORMAT})   # a record no computation gives


_MADE = {}


def pristine_made(epsilon="0/1"):
    """T against T2 at this epsilon, its comparison crate made by `make` once in this process, in a directory of the
    system's temporary files that nothing writes to again; removed when the process ends: (the comparison, T, T2)."""
    if epsilon not in _MADE:
        d = Path(tempfile.mkdtemp(prefix="p3-made-"))
        atexit.register(shutil.rmtree, str(d), True)
        t, t2 = plants_p1.twin_crate(d / "t"), t2_crate(d / "t2")
        p3_compare.make(declaration(t, t2, epsilon), d / "comparison", [t, t2])
        _MADE[epsilon] = (d / "comparison", t, t2)
    return _MADE[epsilon]


def made(d, epsilon="0/1"):
    """A fresh copy of T against T2's comparison, made by `make`, with its two crates, in d: (the comparison, T, T2)."""
    out, t, t2 = pristine_made(epsilon)
    return tuple(Path(shutil.copytree(src, Path(d) / name)) for src, name in
                 ((out, "comparison"), (t, "t/crate"), (t2, "t2/crate")))


def self_compare(d):
    t = plants_p1.twin_crate(Path(d) / "t")
    return Compared(str(hand_written(Path(d) / "comparison", declaration(t, t), PLACEHOLDER)), (str(t),))


def resealed_compare(d):
    t = plants_p1.twin_crate(Path(d) / "t")
    r = plants_p1.shot_moved_resealed(plants_p1.twin_crate(Path(d) / "r"))
    return Compared(str(hand_written(Path(d) / "comparison", declaration(t, r), PLACEHOLDER)), (str(t), str(r)))


def shared_control(d):
    out, t, t2 = made(d)
    return Compared(str(out), (str(t), str(t2)))


def joint_omission(d):
    """The comparison of T against T2 at epsilon 1/20, its record rewritten: x0x1 carries per-cause tolerance checks
    that each pass (Kourousias et al.'s S1.4 numbers, routing alone 0.0417 and angle bias alone 0.0497, each within
    0.05) and the verdict they would compose, `agree`, where the data give `unresolved`. The metadata regenerated, its
    header kept, so the nine steps accept the crate."""
    out, t, t2 = made(d, epsilon="1/20")
    tamper(out, lambda m: m.update(causeChecks=CAUSE_CHECKS, means="agree") if m["measure"] == "x0x1" else None)
    return Compared(str(out), (str(t), str(t2)))


def tamper(comparison, edit):
    """The comparison crate's record, each measure's entry edited by `edit`, and its metadata regenerated by its
    generator, the root's header kept: what a forger who held the comparison crate could do."""
    record = json.loads(plants_p1.read_file(comparison, p3_record.RECORD))
    for m in record["measures"]:
        edit(m)
    plants_p1.write_file(comparison, p3_record.RECORD, p3_record.dumps(record))
    old = plants_p1.graph_of(comparison)["@graph"][1]
    md = p3_record.generate(comparison)
    md["@graph"][1].update({k: old[k] for k in V.HEADER_KEYS if k in old})
    plants_p1.write_file(comparison, canonical.DESCRIPTOR, canonical.write(md))
    return comparison


def readout_unbounded(d):
    out, t, t2 = made(d)
    return Compared(str(out), (str(t), str(t2)))


def said_of(planted, measures=COHERENCES):
    """The sentences a comparison's record says of the measures it names that are not refused: the sentences of the
    statement words it lists, from the vocabulary."""
    record = json.loads(Path(planted.comparison_dir).joinpath(*p3_record.RECORD.split("/")).read_bytes())
    out = set()
    for m in record["measures"]:
        if m["measure"] in measures and m["refused"] == "none":
            out |= {V.WORDS["statement"][w] for w in m["statements"]}
    return frozenset(out)


