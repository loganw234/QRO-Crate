"""P2's controls on v0's real IBM crate (P2's design, item 12; P2.2): `compile-broken` planted in each device's law gate
list by controls/plants_p2.py, in a copy of the crate whose files are hard links to the built one's (the toolkit's
link_copy; every write unlinks first, so the built crate is never written through): one sx of the device's morning law
gate list made an x, every copy of that list in the device's bundles given the new bytes, every manifest's digest of it
and every digest of those manifests recomputed, and the metadata regenerated by P1's generator. The whole checker refuses
each `compile-uncontrolled`, at the device's morning law gate list, by simulating it; and `class-declared`, planted in a
copy the same way, is refused `measure-class` at its Contrast."""
import json

import pytest

import p2crates_support as S
from controls import plants_p1 as toolkit
from controls import plants_p2
from qro import canonical, checker
from qro.refusal import Refused

# The device's first sx at or after gate 303 of its morning law gate list: kingston's is the twin's, gate 303.
FIRST_SX = {"ibm_kingston": (303, 47), "ibm_marrakesh": (303, 9), "ibm_fez": (304, 142)}


def refusal(crate):
    checker.load()
    with pytest.raises(Refused) as x:
        checker.check(crate)
    return x.value


@pytest.mark.parametrize("device", S.DEVICES)
def test_compile_broken_on_each_devices_law_gate_list_is_refused_at_it(tmp_path, device):
    real = S.built("ibm")[0]
    rel = f"2026-10-05/ibm/{device}/bundle/law.gates.json"
    gate, qubit = FIRST_SX[device]
    gates = json.loads(toolkit.read_file(real, rel))["gates"]
    assert [g[0] for g in gates[303:gate]] == ["rz"] * (gate - 303), "no sx before the one planted"
    before = {p: toolkit.read_file(real, p) for p in (rel, canonical.DESCRIPTOR)}
    copies = [p.relative_to(real).as_posix() for p in sorted(real.rglob("law.gates.json"))
              if p.read_bytes() == before[rel]]
    crate = plants_p2.break_gate_list(toolkit.link_copy(real, tmp_path), rel, gate, ["sx", [qubit], [], []],
                                      ["x", [qubit], [], []])
    broken = toolkit.read_file(crate, rel)
    assert len(copies) == (9 if device == "ibm_kingston" else 11)
    assert all(toolkit.read_file(crate, p) == broken for p in copies), "every copy of the device's list is broken"
    r = refusal(crate)
    assert (r.name, r.where) == ("compile-uncontrolled", rel)
    assert r.detail.startswith("the gate list of law does not pass the exact hold: (a) its distribution differs from "
                               "its logical circuit's by "), r.detail
    assert {p: toolkit.read_file(real, p) for p in before} == before, "the built crate is never written through"


def test_class_declared_on_the_real_crate_is_refused_at_its_contrast(tmp_path):
    real = S.built("ibm")[0]
    crate = plants_p2.class_declared(toolkit.link_copy(real, tmp_path))
    r = refusal(crate)
    assert (r.name, r.where) == ("measure-class", f"{plants_p2.CONTRAST} qro:class")
    assert toolkit.read_file(real, canonical.DESCRIPTOR) != toolkit.read_file(crate, canonical.DESCRIPTOR)
